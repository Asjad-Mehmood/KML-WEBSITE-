  const playCodeId = useId();
  const playEastingId = useId();
  const playNorthingId = useId();
  const playElevId = useId();
  const playSysId = useId();

  const applyPreset = (key: string) => {
    const p = PRESETS[key];
    if (!p) return;
    setSelectedPreset(key);
    setCoordSystem(key);
    setStationId(p.station);
    setFeatureCode(p.code);
    setEasting(p.easting);
    setNorthing(p.northing);
    setElevation(p.elev);
  };

