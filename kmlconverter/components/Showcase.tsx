  const dE = (easting || 0) - currentPreset.easting;
  const dN = (northing || 0) - currentPreset.northing;
  const computedLat = (currentPreset.lat + dN / 111320).toFixed(6);
  const computedLon = (
    currentPreset.lon +
    dE / (111320 * Math.cos((currentPreset.lat * Math.PI) / 180))
  ).toFixed(6);

  const radarOffsetX = Math.max(-42, Math.min(42, dE / 22));
  const radarOffsetY = Math.max(-42, Math.min(42, -dN / 22));

  // Gated KML file generation
